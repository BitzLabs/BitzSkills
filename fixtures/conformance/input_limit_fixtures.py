"""Fixed input dimension evidence: size, count and unknown workspace entries.

No Core reader, YAML loader or limit check is implemented here. Inputs are built
from reviewed constants and the generated bytes are measured again against the
documented limits, so each fixture crosses exactly one dimension and no other.
"""
